import {readFile,writeFile} from 'node:fs/promises';
import {generateSQLiteDrizzleJson} from 'drizzle-kit/api';
import * as schema from '../db/schema.ts';
const previous=JSON.parse(await readFile('drizzle/meta/0005_snapshot.json','utf8'));
const snapshot=await generateSQLiteDrizzleJson(schema,previous.id);
await writeFile('drizzle/meta/0006_snapshot.json',JSON.stringify(snapshot,null,2)+'\n');
const journal=JSON.parse(await readFile('drizzle/meta/_journal.json','utf8'));
if(!journal.entries.some(entry=>entry.tag==='0006_email_accounts'))journal.entries.push({idx:6,version:'6',when:Date.now(),tag:'0006_email_accounts',breakpoints:true});
await writeFile('drizzle/meta/_journal.json',JSON.stringify(journal,null,2)+'\n');
console.log('Email-account migration registered.');
