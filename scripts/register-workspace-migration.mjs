import {readFile,writeFile} from 'node:fs/promises';
import {generateSQLiteDrizzleJson} from 'drizzle-kit/api';
import * as schema from '../db/schema.ts';
const previous=JSON.parse(await readFile('drizzle/meta/0003_snapshot.json','utf8'));
const snapshot=await generateSQLiteDrizzleJson(schema,previous.id);
await writeFile('drizzle/meta/0004_snapshot.json',JSON.stringify(snapshot,null,2)+'\n');
const journal=JSON.parse(await readFile('drizzle/meta/_journal.json','utf8'));
if(!journal.entries.some(e=>e.tag==='0004_msds_workspace'))journal.entries.push({idx:4,version:'6',when:1792990800000,tag:'0004_msds_workspace',breakpoints:true});
await writeFile('drizzle/meta/_journal.json',JSON.stringify(journal,null,2)+'\n');
console.log('MSDS workspace schema registered');
